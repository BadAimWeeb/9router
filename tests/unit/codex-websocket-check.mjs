import assert from "node:assert/strict";
import http from "node:http";
import net from "node:net";
import { createRequire } from "node:module";
import { once } from "node:events";

const require = createRequire(import.meta.url);
const { WebSocket } = require("ws");
const upgrade = require("../../realtime/codex-websocket.js");
let output, audio, setups = 0, releaseUpload;
const uploads = [];
const server = http.createServer((req, res) => {
  if (req.headers.authorization !== "Bearer test") { res.writeHead(401).end(); return; }
  if (req.url === "/v1/codex-voice?format=pcm16") {
    setups++;
    output = res;
    res.writeHead(200, { "content-type": "application/x-ndjson" });
    res.write(JSON.stringify({ type: "session", id: "abc" }) + "\n");
  } else {
    const chunks = [];
    req.on("data", (chunk) => chunks.push(chunk));
    req.on("end", () => { audio = Buffer.concat(chunks); uploads.push({ url: req.url, body: audio }); if (!releaseUpload) releaseUpload = () => res.writeHead(204).end(); else res.writeHead(204).end(); });
  }
});
server.on("upgrade", (req, socket, head) => { if (!upgrade(server, req, socket, head)) socket.destroy(); });
server.listen(0, "127.0.0.1");
await once(server, "listening");
const url = `ws://127.0.0.1:${server.address().port}/v1/codex-voice/ws?model=cx%2Fgpt-live-1-codex`;
assert.equal(upgrade(server, { url: "/other" }, {}, null), false);
const connect = (headers) => new WebSocket(url, { headers });
const invalid = net.connect(server.address().port, "127.0.0.1");
await once(invalid, "connect");
invalid.end("GET /v1/codex-voice/ws?model=cx%2Fgpt-live-1-codex HTTP/1.1\r\nHost: localhost\r\nConnection: Upgrade\r\nUpgrade: websocket\r\nAuthorization: Bearer test\r\n\r\n");
let rejected = "";
for await (const chunk of invalid) rejected += chunk;
assert.match(rejected, /^HTTP\/1\.1 400/);
assert.equal(setups, 0);
for (const query of ["&model=other", "&model=cx%2Fgpt-live-1-codex"]) {
  const duplicate = new WebSocket(url + query, { headers: { authorization: "Bearer test" } });
  duplicate.on("error", () => {});
  assert.equal((await once(duplicate, "unexpected-response"))[1].statusCode, 400);
  duplicate.terminate();
}
const bad = connect({ authorization: "Bearer wrong" });
bad.on("error", () => {});
assert.equal((await once(bad, "unexpected-response"))[1].statusCode, 401);
bad.terminate();
const badRealtime = new WebSocket(url.replace("/v1/codex-voice/ws", "/v1/realtime"), { headers: { authorization: "Bearer wrong" } });
badRealtime.on("error", () => {});
assert.equal((await once(badRealtime, "unexpected-response"))[1].statusCode, 401);
badRealtime.terminate();
const origin = connect({ authorization: "Bearer test", origin: "https://example.com" });
origin.on("error", () => {});
assert.equal((await once(origin, "unexpected-response"))[1].statusCode, 400);
origin.terminate();
const ws = connect({ authorization: "Bearer test" });
await once(ws, "open");
output.write(JSON.stringify({ type: "event", event: { type: "upstream.ready" } }) + "\n");
assert.equal(JSON.parse((await once(ws, "message"))[0]).type, "upstream.ready");
ws.send(JSON.stringify({ type: "input_audio_buffer.append", audio: "AQI=" }));
ws.send(JSON.stringify({ type: "input_audio_buffer.append", audio: "AwQ=" }));
output.write(JSON.stringify({ type: "audio", payload: "AwQ=" }) + "\n");
assert.deepEqual(JSON.parse((await once(ws, "message"))[0]), { type: "9router.audio.delta", audio: "AwQ=" });
await new Promise((resolve) => setTimeout(resolve, 30));
assert.deepEqual(audio, Buffer.from([1, 2]));
releaseUpload();
await new Promise((resolve) => setTimeout(resolve, 30));
assert.deepEqual(audio, Buffer.from([3, 4]));
ws.send(JSON.stringify({ type: "response.create" }));
await once(ws, "close");
const rt = new WebSocket(url.replace("/v1/codex-voice/ws", "/v1/realtime"), { headers: { authorization: "Bearer test" } });
const events = [];
rt.on("message", (data) => events.push(JSON.parse(data)));
await once(rt, "open");
while (!events.length) await once(rt, "message");
assert.equal(events[0].type, "session.created");
assert.notEqual(events[0].session.id, "abc");
rt.send(JSON.stringify({ type: "response.create", event_id: "client_1" }));
await once(rt, "message");
assert.equal(events.at(-1).type, "error");
assert.equal(events.at(-1).error.event_id, "client_1");
rt.send("not json");
await once(rt, "message");
assert.equal(events.at(-1).error.event_id, null);
rt.send(JSON.stringify({ type: "input_audio_buffer.append", audio: "BQY=", event_id: "client_2" }));
rt.send(JSON.stringify({ type: "response.cancel", event_id: "client_3" }));
output.write(JSON.stringify({ type: "audio", payload: "AwQ=" }) + "\n");
output.write(JSON.stringify({ type: "event", event: { type: "turn.done", turn: { role: "user", transcript: "hello" } } }) + "\n");
await new Promise((resolve) => setTimeout(resolve, 30));
assert.equal(events.some((event) => event.type === "response.created"), false);
output.write(JSON.stringify({ type: "event", event: { type: "turn.done", turn: { role: "assistant", transcript: "hello back" } } }) + "\n");
while (!events.some((event) => event.type === "response.output_audio_transcript.done")) await once(rt, "message");
const delta = events.find((event) => event.type === "response.output_audio.delta");
assert.equal(delta.delta, "AwQ=");
assert.match(delta.response_id, /^resp_/);
assert.match(delta.item_id, /^item_/);
assert.deepEqual(events.find((event) => event.type === "response.content_part.added").part, { type: "audio" });
assert.equal(events.at(-1).transcript, "hello back");
output.write(JSON.stringify({ type: "event", event: { type: "response.done", response: { status: "completed" } } }) + "\n");
output.write(JSON.stringify({ type: "audio", payload: "BQY=" }) + "\n");
while (!events.some((event) => event.type === "response.done")) await once(rt, "message");
assert.equal(events.filter((event) => event.type === "response.output_audio.delta").length, 2);
assert.equal(events.at(-1).response.status, "incomplete");
assert.equal(events.at(-1).response.id, delta.response_id);
assert.deepEqual(events.at(-1).response.status_details, { type: "incomplete" });
assert.deepEqual(events.at(-1).response.output[0].content, [{ type: "output_audio", transcript: "hello back" }]);
assert.equal(events.at(-1).response.output[0].status, "incomplete");
assert.equal(events.at(-1).response.output[0].id, delta.item_id);
output.write(JSON.stringify({ type: "audio", payload: "Bwg=" }) + "\n");
await new Promise((resolve) => setTimeout(resolve, 30));
assert.equal(events.filter((event) => event.type === "response.created").length, 1);
output.write(JSON.stringify({ type: "event", event: { type: "turn.done", turn: { role: "assistant", transcript: "next" } } }) + "\n");
while (events.filter((event) => event.type === "response.created").length < 2) await once(rt, "message");
assert.notEqual(events.at(-1).response_id, delta.response_id);
output.write(JSON.stringify({ type: "event", event: { type: "turn.done", turn: { role: "user", transcript: "interrupt" } } }) + "\n");
output.write(JSON.stringify({ type: "event", event: { type: "turn.done", turn: { role: "assistant", transcript: "third" } } }) + "\n");
while (events.filter((event) => event.type === "response.created").length < 3) await once(rt, "message");
const second = events.filter((event) => event.type === "response.created")[1].response.id;
assert.equal(events.filter((event) => event.type === "response.done").find((event) => event.response.id === second).response.output[0].content[0].transcript, "next");
output.write(JSON.stringify({ type: "audio", payload: "bad!" }) + "\n");
await once(rt, "close");
await new Promise((resolve) => setTimeout(resolve, 30));
assert.deepEqual(uploads.at(-2), { url: "/v1/codex-voice?session=abc&action=audio", body: Buffer.from([5, 6]) });
assert.equal(uploads.at(-1).url, "/v1/codex-voice?session=abc&action=cancel");
const count = events.length;
await new Promise((resolve) => setTimeout(resolve, 300));
assert.equal(events.length, count);
server.close();
console.log("codex websocket checks passed");